#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const topicRoot = path.join(ROOT, "topics");
const outPath = path.join(ROOT, "docs/ENH-006-QUALITY-REPORT.md");

function* walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(p);
    else if (entry.isFile() && entry.name.endsWith(".json")) yield p;
  }
}

const bySubject = new Map();
let substantive = 0;
let scaffold = 0;
let missing = 0;

for (const file of walk(topicRoot)) {
  const entity = JSON.parse(fs.readFileSync(file, "utf8"));
  const subject = path.relative(topicRoot, file).split(path.sep)[0];
  const row = bySubject.get(subject) || { topics: 0, substantive: 0, scaffold: 0, missing: 0 };
  row.topics++;
  const enhancement = entity?.content?.enhancement;
  if (!enhancement) {
    row.missing++;
    missing++;
  } else {
    const notes = enhancement.verification?.notes;
    const noteText = Array.isArray(notes) ? notes.join(" ") : String(notes || "");
    const thin =
      noteText.includes("No case law invented") ||
      noteText.includes("Existing migrated topic text only") ||
      noteText.includes("Assembled from this topic") ||
      enhancement.coverage === "assembled-from-migrated" ||
      String(enhancement.definition || "").includes("No additional legal rule was generated");
    if (thin) {
      row.scaffold++;
      scaffold++;
    } else {
      row.substantive++;
      substantive++;
    }
  }
  bySubject.set(subject, row);
}

const lines = [
  "# ENH-006 enhancement quality report",
  "",
  "Generated by `scripts/audit-enhancement-quality.mjs`.",
  "",
  "A topic is **substantive** only when its enhancement was not the additive scaffold from existing overview text.",
  "Scaffold topics remain `in-progress` and are not verified.",
  "",
  `| Metric | Count |`,
  `|---|---:|`,
  `| Substantive enhancements | ${substantive} |`,
  `| Scaffold enhancements | ${scaffold} |`,
  `| Missing enhancement object | ${missing} |`,
  "",
  "| Subject | Topics | Substantive | Scaffold | Missing |",
  "|---|---:|---:|---:|---:|",
];
for (const [subject, row] of [...bySubject.entries()].sort()) {
  lines.push(`| ${subject} | ${row.topics} | ${row.substantive} | ${row.scaffold} | ${row.missing} |`);
}
lines.push("");
fs.writeFileSync(outPath, lines.join("\n"));
console.log(`ENH-006: substantive=${substantive} scaffold=${scaffold} missing=${missing}`);
console.log(`Wrote ${path.relative(ROOT, outPath)}`);
