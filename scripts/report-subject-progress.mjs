#!/usr/bin/env node
/** ENH-009: subject-level sprint progress. Substantive means not a scaffold. */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const topicRoot = path.join(ROOT, "topics");
const outPath = path.join(ROOT, "docs/ENH-009-SUBJECT-PROGRESS.md");

function isScaffold(enhancement) {
  const notes = enhancement.verification?.notes;
  const noteText = Array.isArray(notes) ? notes.join(" ") : String(notes || "");
  return (
    noteText.includes("No case law invented") ||
    noteText.includes("Existing migrated topic text only") ||
    noteText.includes("Assembled from this topic") ||
    enhancement.coverage === "assembled-from-migrated" ||
    String(enhancement.definition || "").includes("No additional legal rule was generated")
  );
}

const rows = [];
for (const subject of fs.readdirSync(topicRoot).sort()) {
  const dir = path.join(topicRoot, subject);
  if (!fs.statSync(dir).isDirectory()) continue;
  let topics = 0;
  let substantive = 0;
  let verified = 0;
  for (const name of fs.readdirSync(dir)) {
    if (!name.endsWith(".json")) continue;
    topics++;
    const entity = JSON.parse(fs.readFileSync(path.join(dir, name), "utf8"));
    const enhancement = entity?.content?.enhancement;
    if (!enhancement) continue;
    if (enhancement.status === "verified" || enhancement.status === "published") verified++;
    if (!isScaffold(enhancement)) substantive++;
  }
  const pct = topics ? Math.round((substantive / topics) * 100) : 0;
  const track = verified === topics && topics > 0 ? "VERIFIED" : substantive === topics && topics > 0 ? "SUBSTANTIVE" : substantive > 0 ? "PARTIAL" : "SCAFFOLD";
  rows.push({ subject, topics, substantive, verified, pct, track });
}

const lines = [
  "# ENH-009 subject progress",
  "",
  "Generated by `scripts/report-subject-progress.mjs`.",
  "Sprint tracking uses substantive coverage, not the presence of an enhancement object.",
  "VERIFIED requires every topic in the subject to be verified or published. None are.",
  "",
  "| Subject | Topics | Substantive | Verified | Substantive % | Track |",
  "|---|---:|---:|---:|---:|---|",
];
for (const row of rows) {
  lines.push(`| ${row.subject} | ${row.topics} | ${row.substantive} | ${row.verified} | ${row.pct} | ${row.track} |`);
}
lines.push("");
fs.writeFileSync(outPath, lines.join("\n"));
console.log(`ENH-009: subjects=${rows.length}`);
console.log(`Wrote ${path.relative(ROOT, outPath)}`);
