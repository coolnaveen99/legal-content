#!/usr/bin/env node
/**
 * ENH-008: write a per-batch validation artifact.
 * A batch is one subject family under topics/<subject>.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const topicRoot = path.join(ROOT, "topics");
const outDir = path.join(ROOT, "docs/batches");
const outPath = path.join(outDir, "ENH-008-BATCH-VALIDATION.md");
fs.mkdirSync(outDir, { recursive: true });

function files(dir) {
  return fs.readdirSync(dir).filter((name) => name.endsWith(".json")).sort();
}

const rows = [];
for (const subject of fs.readdirSync(topicRoot).sort()) {
  const dir = path.join(topicRoot, subject);
  if (!fs.statSync(dir).isDirectory()) continue;
  let topics = 0;
  let enhanced = 0;
  let substantive = 0;
  let scaffold = 0;
  let invalid = 0;
  for (const name of files(dir)) {
    topics++;
    let entity;
    try {
      entity = JSON.parse(fs.readFileSync(path.join(dir, name), "utf8"));
    } catch {
      invalid++;
      continue;
    }
    const enhancement = entity?.content?.enhancement;
    if (!enhancement) continue;
    enhanced++;
    const notes = enhancement.verification?.notes;
    const noteText = Array.isArray(notes) ? notes.join(" ") : String(notes || "");
    const thin =
      noteText.includes("No case law invented") ||
      noteText.includes("Existing migrated topic text only") ||
      noteText.includes("Assembled from this topic") ||
      enhancement.coverage === "assembled-from-migrated" ||
      String(enhancement.definition || "").includes("No additional legal rule was generated");
    if (thin) scaffold++;
    else substantive++;
    if (!enhancement.status || !enhancement.definition) invalid++;
  }
  const gate = invalid === 0 && enhanced === topics ? "PASS" : "FAIL";
  rows.push({ subject, topics, enhanced, substantive, scaffold, invalid, gate });
}

const lines = [
  "# ENH-008 per-batch validation",
  "",
  "Generated by `scripts/report-enhancement-batches.mjs`.",
  "A batch passes the structural gate when every topic has an enhancement object and valid JSON.",
  "PASS does not mean verified. Scaffold rows are still in-progress.",
  "",
  "| Batch | Topics | Enhanced | Substantive | Scaffold | Invalid | Gate |",
  "|---|---:|---:|---:|---:|---:|---|",
];
for (const row of rows) {
  lines.push(`| ${row.subject} | ${row.topics} | ${row.enhanced} | ${row.substantive} | ${row.scaffold} | ${row.invalid} | ${row.gate} |`);
}
lines.push("");
fs.writeFileSync(outPath, lines.join("\n"));
const failed = rows.filter((row) => row.gate === "FAIL").length;
console.log(`ENH-008: batches=${rows.length} failed=${failed}`);
console.log(`Wrote ${path.relative(ROOT, outPath)}`);
process.exit(failed ? 1 : 0);
